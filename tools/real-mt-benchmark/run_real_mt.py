#!/usr/bin/env python3
"""
Run the REAL OPUS-MT (MarianMT) over the safety corpus and emit genuine model outputs.

This is the linchpin of VoxBridge's empirical claim: the safety numbers must be measured
against what the ACTUAL production translation model does, not a simulated failure injection.
The model is Helsinki-NLP/opus-mt-{vi-en,en-vi} (the same OPUS-MT family the design ships as
INT8 on ONNX Runtime). Here it runs in fp32 on CPU purely to capture its TEXT output; the Kotlin
DecisionEngine that consumes this output is byte-identical to the on-device safety layer.

Output: outputs.tsv  with columns  id  src  tgt  source  model_out  required  safety  note
The Kotlin harness reads this and drives the real engine over the real model text.

No device, no QNN, no AI Hub needed — torch CPU only.
"""
import sys
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent
CORPUS = HERE / "corpus.tsv"
OUT = HERE / "outputs.tsv"

EN_VI = "Helsinki-NLP/opus-mt-en-vi"
VI_EN = "Helsinki-NLP/opus-mt-vi-en"


def main() -> int:
    t0 = time.time()
    try:
        import torch
        from transformers import AutoTokenizer, AutoModelForSeq2SeqLM
    except Exception as e:  # noqa: BLE001
        sys.stderr.write(f"[blocked] torch/transformers unavailable: {e}\n")
        return 2

    torch.set_num_threads(4)

    cache: dict[str, tuple] = {}

    def load(name: str):
        if name not in cache:
            tok = AutoTokenizer.from_pretrained(name)
            mdl = AutoModelForSeq2SeqLM.from_pretrained(name)
            mdl.eval()
            cache[name] = (tok, mdl)
        return cache[name]

    def translate(text: str, src: str, tgt: str) -> str:
        name = EN_VI if (src == "EN" and tgt == "VI") else VI_EN
        tok, mdl = load(name)
        batch = tok([text], return_tensors="pt", padding=True)
        with torch.no_grad():
            gen = mdl.generate(**batch, max_length=80, num_beams=4)
        return tok.batch_decode(gen, skip_special_tokens=True)[0].strip()

    rows = []
    for line in CORPUS.read_text(encoding="utf-8").splitlines():
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        parts = line.split("\t")
        # id src tgt source required safety note  (required/note may be empty)
        while len(parts) < 7:
            parts.append("")
        cid, src, tgt, source, required, safety, note = parts[:7]
        out = translate(source, src, tgt)
        rows.append((cid, src, tgt, source, out, required, safety, note))
        sys.stderr.write(f"  {cid:7s} {src}->{tgt}  {source!r} => {out!r}\n")
        sys.stderr.flush()

    with OUT.open("w", encoding="utf-8") as f:
        f.write("# id\tsrc\ttgt\tsource\tmodel_out\trequired\tsafety\tnote\n")
        f.write(f"# generated by run_real_mt.py over {EN_VI} + {VI_EN} (fp32 CPU); text output only\n")
        for r in rows:
            f.write("\t".join(r) + "\n")

    sys.stderr.write(f"[ok] wrote {len(rows)} rows to {OUT} in {time.time()-t0:.1f}s\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
